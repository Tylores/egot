#!/bin/bash
# Generate route registration tests for all 23 microservices

set -e

TESTDATA_DIR="test/testdata"
CMD_DIR="cmd"

# Color codes
GREEN='\033[0;32m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo "Generating route registration test files for all services..."
echo ""

# Function to generate a test file for a service
generate_test_file() {
    local service=$1
    local json_file=$2
    local output_file="${CMD_DIR}/${service}/${service,,}_route_registration_test.go"

    # Skip if JSON doesn't exist
    if [ ! -f "$json_file" ]; then
        echo -e "${BLUE}⊘${NC} $service: No test data (skipping)"
        return
    fi

    # Extract route count from JSON
    local route_count=$(grep -o '"total_routes": [0-9]*' "$json_file" | grep -o '[0-9]*')
    
    if [ -z "$route_count" ] || [ "$route_count" -eq 0 ]; then
        echo -e "${BLUE}⊘${NC} $service: No routes in testdata (skipping)"
        return
    fi

    # Create output directory if needed
    mkdir -p "$(dirname "$output_file")"

    # Write the test file
    cat > "$output_file" << TESTEOF
// Code generated by generate_all_service_tests.sh; DO NOT EDIT.
