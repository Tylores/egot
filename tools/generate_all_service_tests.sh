    echo -e "${GREEN}✓${NC} $service: $route_count routes -> $output_file"
}

# Get list of services from existing cmd directories
total_generated=0
while IFS= read -r dir; do
    if [ -d "$dir" ]; then
        service=$(basename "$dir")
        json_file="${TESTDATA_DIR}/${service,,}_routes.json"
        
        # Handle special naming conventions
        case "${service}" in
            Bill) json_file="${TESTDATA_DIR}/bill_routes.json" ;;
            BRS) json_file="${TESTDATA_DIR}/brs_routes.json" ;;
            DCAP) json_file="${TESTDATA_DIR}/dcap_routes.json" ;;
            DERP) json_file="${TESTDATA_DIR}/derp_routes.json" ;;
            DR) json_file="${TESTDATA_DIR}/dr_routes.json" ;;
            EDevice) json_file="${TESTDATA_DIR}/edev_routes.json" ;;
            File) json_file="${TESTDATA_DIR}/file_routes.json" ;;
            MUP) json_file="${TESTDATA_DIR}/mup_routes.json" ;;
            Messaging) json_file="${TESTDATA_DIR}/msg_routes.json" ;;
            Notify) json_file="${TESTDATA_DIR}/ntfy_routes.json" ;;
            PPY) json_file="${TESTDATA_DIR}/ppy_routes.json" ;;
            SDevice) json_file="${TESTDATA_DIR}/sdev_routes.json" ;;
            TariffProfile) json_file="${TESTDATA_DIR}/tp_routes.json" ;;
            TimeOfUse) json_file="${TESTDATA_DIR}/tm_routes.json" ;;
            UPT) json_file="${TESTDATA_DIR}/upt_routes.json" ;;
        esac
        
        if [ -f "$json_file" ]; then
            generate_test_file "$service" "$json_file"
            ((total_generated++)) || true
        fi
    fi
done < <(find "${CMD_DIR}" -maxdepth 1 -type d | sort | tail -n +2)

echo ""
echo -e "${GREEN}✅ Generated test files for ${total_generated} service(s)${NC}"
echo ""
echo "Next steps:"
echo "  1. Review generated test files in cmd/<Service>/*_route_registration_test.go"
echo "  2. Implement test logic by loading expectations from test/testdata/"
echo "  3. Run tests: go test ./cmd/..."
